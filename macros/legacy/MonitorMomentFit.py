def run_calculate_acceptance(
    tbin_name: str,
    tbin_dir: str,
    root_filename: str | None = None,
    max_l: int = 4
) -> bool:
    """Run CalculateAcceptance_m080200.C via ROOT for a converged t-bin.

    Returns True if acceptance.root was successfully created or updated.
    """
    tbin_index_map = {
        "t010020": 0,
        "t020032": 1,
        "t0200325": 1,
        "t032050": 2,
        "t0325050": 2,
        "t050075": 3,
        "t075100": 4
    }
    tbin_idx = tbin_index_map.get(tbin_name)
    if tbin_idx is None:
        m = re.search(r'\d+', tbin_name)
        if m and 0 <= int(m.group(0)) <= 4:
            tbin_idx = int(m.group(0))
        else:
            print(f"Warning: Could not determine tbin index for '{tbin_name}'. Skipping acceptance calculation.")
            return False

    brufit_load = None
    for cand in [
        "/d/grid17/septian/brufit_dev/brufit_cov/macros/LoadBru.C",
        os.environ.get("BRUFIT", "") + "/macros/LoadBru.C",
        "/d/home/septian/brufit/macros/LoadBru.C",
        "/d/grid17/septian/brufit/macros/LoadBru.C"
    ]:
        if cand and os.path.isfile(cand):
            brufit_load = cand
            break

    if not brufit_load:
        print("Warning: BruFit LoadBru.C not found. Skipping acceptance calculation.")
        return False

    macro_path = None
    for cand in [
        "/d/home/septian/EtaPi0Analysis/macros/CalculateAcceptance_m080200.C",
        "/d/grid17/septian/EtaPi0Analysis/macros/CalculateAcceptance_m080200.C",
        "/d/home/septian/Moments2Amplitudes/macros/CalculateAcceptance_m080200.C"
    ]:
        if os.path.isfile(cand):
            macro_path = cand
            break

    if not macro_path:
        print("Warning: CalculateAcceptance_m080200.C not found. Skipping acceptance calculation.")
        return False

    macro_dir = os.path.dirname(macro_path)
    res_file = root_filename if root_filename else "ResultsBruMcmcFixedCovariance.root"

    # Command string with BruFit and ROOT environment sourcing
    env_source = ""
    if os.path.isfile("/d/grid17/septian/brufit_dev/brufit_cov/set_env.sh"):
        env_source += "source /d/grid17/septian/brufit_dev/brufit_cov/set_env.sh && "
    if shutil.which("root") is None and os.path.isfile("/d/grid17/septian/root_v6-36-08_cuda_install/bin/thisroot.sh"):
        env_source += "source /d/grid17/septian/root_v6-36-08_cuda_install/bin/thisroot.sh && "

    root_cmd = f'{env_source}root -l -b -q {brufit_load} \'{macro_path}({tbin_idx}, "{tbin_dir}", "{res_file}", {max_l})\''

    print(f"\n--- Running CalculateAcceptance_m080200.C for {tbin_name} ---")
    print(f"Command: {root_cmd}")

    try:
        proc = subprocess.run(
            root_cmd,
            shell=True,
            cwd=macro_dir,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True
        )
        lines = [line.strip() for line in proc.stdout.splitlines() if line.strip()]
        for line in lines[-10:]:
            print(f"  [Acceptance] {line}")

        acceptance_file = os.path.join(tbin_dir, "acceptance.root")
        if os.path.isfile(acceptance_file):
            print(f"✅ Acceptance successfully saved to: {acceptance_file}")
            return True
        else:
            print(f"⚠️  Acceptance run finished, but {acceptance_file} was not found.")
            return False
    except Exception as e:
        print(f"ERROR running acceptance calculation: {e}")
        return False


def discover_tbin_directories(base_dir: str, tbin_filter: str) -> list[tuple[str, str]]:
    """
    Given a directory and a tbin filter, find all matching (tbin_name, full_path) pairs.
    """
    # Check if base_dir itself is directly a t-bin folder (contains Mpi0eta* subdirs or logRooFit*.txt)
    direct_logs = glob.glob(os.path.join(base_dir, "logRooFit*.txt"))
    direct_subdirs = [d for d in os.listdir(base_dir) if re.search(r"Mpi0eta[0-9.]+", d)] if os.path.isdir(base_dir) else []

    if direct_logs or direct_subdirs:
        tbin_name = os.path.basename(os.path.normpath(base_dir))
        return [(tbin_name, os.path.abspath(base_dir))]

    # Otherwise search inside base_dir for t-bin directories
    tbin_dirs = []
    if not os.path.isdir(base_dir):
        print(f"ERROR: Run directory '{base_dir}' does not exist.")
        return []

    # Filter target names
    target_names = None
    if tbin_filter.lower() != "all":
        if tbin_filter.isdigit():
            idx = int(tbin_filter)
            target_names = [TBIN_INDEX_MAP.get(idx, f"t{idx}")]
        else:
            target_names = [tbin_filter]

    for entry in sorted(os.listdir(base_dir)):
        p = os.path.join(base_dir, entry)
        if os.path.isdir(p) and re.match(r"t\d{6}", entry):
            if target_names is None or entry in target_names:
                tbin_dirs.append((entry, os.path.abspath(p)))

    return tbin_dirs


def monitor_single_tbin(
    tbin_name: str,
    tbin_dir: str,
    burn_in: int,
    ess_threshold: float,
    output_dir: str | None,
    root_filename: str | None,
    skip_trace: bool,
    skip_posterior: bool,
    skip_moments: bool,
    skip_acceptance: bool = False,
    force_acceptance: bool = False,
    max_l: int = 4
):
    # Output directory defaults directly to the MCMC result directory
    if output_dir is None:
        plot_out_dir = tbin_dir
    else:
        plot_out_dir = os.path.join(output_dir, tbin_name) if os.path.isdir(output_dir) else output_dir
    os.makedirs(plot_out_dir, exist_ok=True)

    diag_log_file = os.path.join(plot_out_dir, f"MomentFit_Diagnostics_{tbin_name}.txt")
    diag_alias_file = os.path.join(plot_out_dir, "MCMC_Diagnostics.txt")

    with tee_to_file(diag_log_file):
        print("\n" + "=" * 100)
        print(f" MONITORING MOMENT FIT: {tbin_name}")
        print(f" Result Directory: {tbin_dir}")
        print(f" Output Location:  {plot_out_dir}")
        print(f" Burn-in:          {burn_in} samples")
        print(f" ESS Threshold:    {ess_threshold:.1f} (Black >= {int(ess_threshold)}, Red < {int(ess_threshold)})")
        print("=" * 100)

        # 1. Initialize MomentsMCMC container with auto-discovery
        print("\n[1/6] Loading MCMC results...")
        try:
            mcmc = FitResults.MomentsMCMC(
                fit_result_dir=tbin_dir,
                root_filename=root_filename,
                burn_in=burn_in
            )
        except Exception as e:
            print(f"ERROR: Failed to initialize MomentsMCMC for {tbin_dir}: {e}")
            return

        n_bins = mcmc.get_N_fit_bins()
        n_loaded = sum(1 for i in range(n_bins) if mcmc.get_rdf(i) is not None)
        print(f"Container initialized: {n_bins} mass bins defined, {n_loaded} successfully loaded.")

        # 2. Print Fit Status Table
        print("\n[2/6] Fit Status Summary Table:")
        status_info = mcmc.print_fit_status(show_diagnostics=True)

        # 3. Print MCMC Chain Diagnostics Summary Table
        print("\n[3/6] MCMC Diagnostics Across Successful Mass Bins:")
        diags = mcmc.print_mcmc_diagnostics()

        # Flag low ESS bins / moments
        low_ess_report = []
        if diags:
            for b_idx, d in sorted(diags.items()):
                m_val = d['mass']
                per_m = d['per_moment']
                bad_moments = [(m_name, vals['ess']) for m_name, vals in per_m.items() if vals['ess'] < ess_threshold]
                if bad_moments:
                    bad_moments.sort(key=lambda x: x[1])
                    worst_m, worst_ess = bad_moments[0]
                    low_ess_report.append((b_idx, m_val, len(bad_moments), len(per_m), worst_m, worst_ess))

        print("\n" + "-" * 100)
        if low_ess_report:
            print(f"⚠️  Cautionary Bins with ESS < {ess_threshold:.1f} ({len(low_ess_report)} / {len(diags)} successful bins affected):")
            print(f"{'Bin':<5} {'Mass (GeV)':<12} {'Low ESS Moments':<20} {'Worst Moment':<25} {'Worst ESS'}")
            print("-" * 100)
            for b_idx, m_val, n_bad, n_tot, worst_m, worst_ess in low_ess_report:
                m_str = f"{m_val:.4f}" if m_val is not None else "N/A"
                print(f"{b_idx:<5} {m_str:<12} {n_bad}/{n_tot:<18} {worst_m:<25} {worst_ess:.1f}")
            print(f"Note: In the unnormalized moments vs mass plots, points with ESS < {int(ess_threshold)} are colored RED.")
        else:
            print(f"✅ All successful mass bins achieved ESS >= {ess_threshold:.1f} across all moments!")
        print("-" * 100)

        # 4. Generate MCMC Traces
        trace_pdf = os.path.join(plot_out_dir, f"MCMCTrace_{tbin_name}.pdf")
        if not skip_trace:
            print(f"\n[4a/6] Generating MCMC Trace plots -> {trace_pdf}")
            try:
                mcmc.print_all_moment_trace_graph(trace_pdf)
            except Exception as e:
                print(f"Warning: Failed to generate trace plots: {e}")
        else:
            print("\n[4a/6] Skipping MCMC Trace plots (--skip-trace)")

        # 5. Generate Posterior Distributions
        posterior_pdf = os.path.join(plot_out_dir, f"PosteriorDistribution_{tbin_name}.pdf")
        if not skip_posterior:
            print(f"\n[4b/6] Generating Posterior Distribution plots -> {posterior_pdf}")
            try:
                mcmc.print_posterior_distribution_all_bins(posterior_pdf, burn_in=burn_in)
            except Exception as e:
                print(f"Warning: Failed to generate posterior distribution plots: {e}")
        else:
            print("\n[4b/6] Skipping Posterior Distribution plots (--skip-posterior)")

        # 5. Check MCMC Convergence & Calculate Acceptance
        print("\n[5/6] Checking MCMC Fit Convergence for Acceptance Calculation:")
        n_total = len(status_info.get('bins', [])) if status_info else n_bins
        n_success = len(status_info.get('success_bins', [])) if status_info else 0
        all_bins_success = (n_success == n_total and n_total > 0)

        acceptance_file = os.path.join(tbin_dir, "acceptance.root")
        if (all_bins_success or force_acceptance) and not skip_acceptance:
            if not all_bins_success and force_acceptance:
                print(f"⚠️  Caution: Running acceptance calculation because --force-acceptance is set ({n_success}/{n_total} bins succeeded).")
            else:
                print(f"✅ All {n_total} mass bins converged successfully! Running CalculateAcceptance_m080200.C...")

            acc_success = run_calculate_acceptance(
                tbin_name=tbin_name,
                tbin_dir=tbin_dir,
                root_filename=root_filename,
                max_l=max_l
            )
            if acc_success:
                try:
                    mcmc.load_acceptance()
                except Exception as e:
                    print(f"Warning: Could not reload acceptance: {e}")
        else:
            if skip_acceptance:
                print("ℹ️  Skipping acceptance calculation (--skip-acceptance).")
            else:
                print(f"⚠️  MCMC fit was NOT successful in all bins ({n_success}/{n_total} succeeded).")
                print("    Skipping acceptance calculation macro (requires complete convergence).")

            if os.path.isfile(acceptance_file):
                print(f"ℹ️  Found existing {acceptance_file}; will use it for moments.")
                try:
                    mcmc.load_acceptance()
                except Exception as e:
                    print(f"WARNING: Could not load existing acceptance ({e}). Acceptance cannot be loaded.")
                    print("         The unnormalized moments are not yield acceptance corrected.")
            else:
                print(f"WARNING: Acceptance file {acceptance_file} not found. Acceptance cannot be loaded.")
                print("         The unnormalized moments are not yield acceptance corrected.")

        # 6. Generate Unnormalized Moments vs Mass (with Black for ESS >= 100, Red for ESS < 100)
        moments_pdf = os.path.join(plot_out_dir, f"UnnormalizedMoments_vs_Mass_{tbin_name}.pdf")
        moments_root = os.path.join(plot_out_dir, f"UnnormalizedMoments_vs_Mass_{tbin_name}.root")
        if not skip_moments:
            print(f"\n[6/6] Generating Unnormalized Moments vs Mass plots (Black: ESS >= {int(ess_threshold)}, Red: ESS < {int(ess_threshold)}):")
            print(f"      PDF:  {moments_pdf}")
            print(f"      ROOT: {moments_root}")
            try:
                mcmc.print_unnormalized_moments_vs_mass_by_ess(moments_pdf, ess_threshold=ess_threshold, burn_in=burn_in)
                mcmc.save_unnormalized_moments_vs_mass_by_ess(moments_root, ess_threshold=ess_threshold, burn_in=burn_in)
            except Exception as e:
                print(f"Warning: Failed to generate unnormalized moments vs mass plots: {e}")
        else:
            print("\n[6/6] Skipping Unnormalized Moments vs Mass plots (--skip-moments)")

        print("\n" + "=" * 100)
        print(f" COMPLETED MONITORING FOR {tbin_name}")
        print(f" Diagnostic text saved to:  {diag_log_file}")
        print(f" Diagnostic alias:          {diag_alias_file}")
        if not skip_trace:
            print(f" MCMC Traces PDF:           {trace_pdf}")
        if not skip_posterior:
            print(f" Posterior Distributions:   {posterior_pdf}")
        if not skip_moments:
            print(f" Moments vs Mass PDF:       {moments_pdf}")
            print(f" Moments vs Mass ROOT File: {moments_root}")
        print("=" * 100)

    # Save alias copy
    try:
        shutil.copyfile(diag_log_file, diag_alias_file)
    except Exception:
        pass


def main():
    args = parse_arguments()

    run_dir = args.run_dir
    if run_dir is None:
        run_dir = find_default_run_dir()
        if run_dir is None:
            print("ERROR: No run directory specified with --run-dir, and no default MomentFit_m080200* directory found.")
            sys.exit(1)
        print(f"Auto-selected newest run directory: {run_dir}")

    tbin_dirs = discover_tbin_directories(run_dir, args.tbin)
    if not tbin_dirs:
        print(f"ERROR: No t-bin directories found in '{run_dir}' matching tbin='{args.tbin}'.")
        sys.exit(1)

    print(f"Found {len(tbin_dirs)} t-bin directory/directories to process:")
    for name, path in tbin_dirs:
        print(f"  - {name}: {path}")

    for tbin_name, tbin_path in tbin_dirs:
        monitor_single_tbin(
            tbin_name=tbin_name,
            tbin_dir=tbin_path,
            burn_in=args.burn_in,
            ess_threshold=args.ess_threshold,
            output_dir=args.output_dir,
            root_filename=args.root_filename,
            skip_trace=args.skip_trace,
            skip_posterior=args.skip_posterior,
            skip_moments=args.skip_moments,
            skip_acceptance=args.skip_acceptance,
            force_acceptance=args.force_acceptance,
            max_l=args.max_l
        )


if __name__ == "__main__":
    main()
