"""
MonitorMomentFit.py

Automated post-fit monitoring and diagnostics program for BruFit MomentFit results
generated by RunMomentFit_m080200.sh / MomentFit_m080200.C.

Key capabilities:
  1. Print comprehensive fit status table (SUCCESS, FAILED, STALLED, RUNNING).
  2. Compute and print MCMC chain diagnostics:
       - Integrated autocorrelation time (tau_int)
       - Effective Sample Size (ESS) accounting for burn-in.
  3. Flag all moments and bins with low ESS (< threshold, default 100).
  4. Write all diagnostic text directly to the MCMC result directory:
       - MomentFit_Diagnostics_<tbin>.txt (and MCMC_Diagnostics.txt)
  5. Generate publication-ready multi-page diagnostic PDFs directly in the MCMC result directory:
       - MCMCTrace_<tbin>.pdf: Trace steps vs moment values across all bins.
       - PosteriorDistribution_<tbin>.pdf: 1D posterior distributions with mu, sigma, tau, ESS.
       - UnnormalizedMoments_vs_Mass_<tbin>.pdf: Unnormalized moments vs mass distinguishing:
           * BLACK marker: Success with good ESS (ESS >= 100)
           * RED marker:   Success with cautionary low ESS (ESS < 100)
  6. Export unnormalized moments vs mass graphs into a ROOT file for downstream amplitude fits:
       - UnnormalizedMoments_vs_Mass_<tbin>.root

Usage:
  ./MonitorMomentFit.py --run-dir /path/to/run_dir [--tbin all|0|t010020] [--burn-in 2000] [--ess-threshold 100]
"""

