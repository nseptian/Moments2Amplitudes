class TeeLogger:
    """Duplicate stdout to both the console and a text log file."""
    def __init__(self, filepath: str):
        self.terminal = sys.stdout
        self.file = open(filepath, "w", encoding="utf-8")

    def write(self, message):
        self.terminal.write(message)
        self.file.write(message)

    def flush(self):
        self.terminal.flush()
        self.file.flush()

    def close(self):
        self.file.close()


@contextmanager
def tee_to_file(filepath: str):
    logger = TeeLogger(filepath)
    old_stdout = sys.stdout
    sys.stdout = logger
    try:
        yield logger
    finally:
        sys.stdout = old_stdout
        logger.close()


def find_default_run_dir() -> str | None:
    """Find the latest MomentFit run directory if none was specified."""
    search_patterns = [
        "/d/grid17/septian/EtaPi0Analysis/run/MomentFit_m080200*",
        "/d/home/septian/EtaPi0Analysis/run/MomentFit_m080200*"
    ]
    candidates = []
    for pat in search_patterns:
        candidates.extend(glob.glob(pat))

    if not candidates:
        return None

    # Sort by modification time, newest first
    candidates.sort(key=lambda p: os.path.getmtime(p), reverse=True)
    return candidates[0]


